"""Embed Slang source files for runtime compilation."""

import json
from pathlib import Path


def build_slang_header(target, source, env):
    header = Path(target[0].abspath)
    paths = [Path(node.abspath) for node in source]

    with header.open("w", encoding="utf-8", newline="\n") as output:
        output.write("// Generated by slang_builders.py.\n#pragma once\n\n#include <cstddef>\n\n")
        output.write("namespace YutrelEmbeddedShaders {\n\n")
        for index, path in enumerate(paths):
            data = path.read_bytes() + b"\0"
            output.write(f"static constexpr unsigned char source_{index}[] = {{\n")
            for offset in range(0, len(data), 16):
                row = ", ".join(f"0x{byte:02x}" for byte in data[offset : offset + 16])
                output.write(f"\t{row},\n")
            output.write("};\n\n")

        output.write("struct File {\n\tconst char *path;\n\tconst unsigned char *source;\n\tstd::size_t size;\n};\n\n")
        output.write("static constexpr File files[] = {\n")
        for index, path in enumerate(paths):
            relative_path = json.dumps(path.relative_to(header.parent).as_posix(), ensure_ascii=False)
            output.write(f"\t{{ {relative_path}, source_{index}, sizeof(source_{index}) - 1 }},\n")
        output.write("};\n\n} // namespace YutrelEmbeddedShaders\n")
